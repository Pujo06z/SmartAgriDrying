IF DB_ID('SmartAgriDrying') IS NULL
BEGIN
    CREATE DATABASE SmartAgriDrying;
END
GO

USE SmartAgriDrying;
GO

-- Drop in dependency order for rerun
IF OBJECT_ID('EVENT_LOG','U') IS NOT NULL DROP TABLE EVENT_LOG;
IF OBJECT_ID('SENSOR_DATA','U') IS NOT NULL DROP TABLE SENSOR_DATA;
IF OBJECT_ID('DRYING_BATCH','U') IS NOT NULL DROP TABLE DRYING_BATCH;
IF OBJECT_ID('DEVICE','U') IS NOT NULL DROP TABLE DEVICE;
IF OBJECT_ID('USER_WAREHOUSE','U') IS NOT NULL DROP TABLE USER_WAREHOUSE;
IF OBJECT_ID('WAREHOUSE','U') IS NOT NULL DROP TABLE WAREHOUSE;
IF OBJECT_ID('USERS','U') IS NOT NULL DROP TABLE USERS;
GO

CREATE TABLE USERS (
    user_id VARCHAR(10) PRIMARY KEY,
    username VARCHAR(50) UNIQUE NOT NULL,
    password VARCHAR(100) NOT NULL,
    full_name NVARCHAR(100) NOT NULL,
    role VARCHAR(20) NOT NULL CHECK (role IN ('ADMIN','MANAGER','OPERATOR')),
    status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE','INACTIVE')),
    created_at DATETIME2 NOT NULL DEFAULT SYSDATETIME()
);

CREATE TABLE WAREHOUSE (
    warehouse_id VARCHAR(10) PRIMARY KEY,
    warehouse_code VARCHAR(20) UNIQUE NOT NULL,
    warehouse_name NVARCHAR(100) NOT NULL,
    location NVARCHAR(200),
    status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE','INACTIVE')),
    created_at DATETIME2 NOT NULL DEFAULT SYSDATETIME()
);

CREATE TABLE USER_WAREHOUSE (
    user_id VARCHAR(10) NOT NULL,
    warehouse_id VARCHAR(10) NOT NULL,
    assigned_at DATETIME2 NOT NULL DEFAULT SYSDATETIME(),
    status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE','INACTIVE')),
    CONSTRAINT PK_USER_WAREHOUSE PRIMARY KEY (user_id, warehouse_id),
    CONSTRAINT FK_UW_USER FOREIGN KEY (user_id) REFERENCES USERS(user_id),
    CONSTRAINT FK_UW_WAREHOUSE FOREIGN KEY (warehouse_id) REFERENCES WAREHOUSE(warehouse_id)
);

CREATE TABLE DEVICE (
    device_id VARCHAR(10) PRIMARY KEY,
    warehouse_id VARCHAR(10) NOT NULL,
    device_code VARCHAR(30) UNIQUE NOT NULL,
    device_name NVARCHAR(100) NOT NULL,

    mode VARCHAR(20) NOT NULL
        DEFAULT 'AUTO'
        CHECK (mode IN ('AUTO','MANUAL')),

    roof_status VARCHAR(20) NOT NULL
        DEFAULT 'CLOSED'
        CHECK (roof_status IN ('OPEN','CLOSED')),

    last_seen DATETIME2 NULL,

    status VARCHAR(20) NOT NULL
        DEFAULT 'ACTIVE'
        CHECK (status IN ('ACTIVE','INACTIVE')),

    CONSTRAINT FK_DEVICE_WAREHOUSE
        FOREIGN KEY (warehouse_id)
        REFERENCES WAREHOUSE(warehouse_id)
);

CREATE TABLE DRYING_BATCH (
    batch_id VARCHAR(10) PRIMARY KEY,
    warehouse_id VARCHAR(10) NOT NULL,
    operator_id VARCHAR(10) NOT NULL,
    product_name NVARCHAR(100) NOT NULL,
    weight_kg DECIMAL(10,2) NOT NULL CHECK (weight_kg > 0),
    start_time DATETIME2 NOT NULL,
    end_time DATETIME2 NULL,
    status VARCHAR(20) NOT NULL CHECK (status IN ('DRYING','COMPLETED')),
    notes NVARCHAR(500) NULL,
    CONSTRAINT FK_BATCH_WAREHOUSE FOREIGN KEY (warehouse_id) REFERENCES WAREHOUSE(warehouse_id),
    CONSTRAINT FK_BATCH_OPERATOR FOREIGN KEY (operator_id) REFERENCES USERS(user_id),
    CONSTRAINT CK_BATCH_TIME CHECK (end_time IS NULL OR end_time >= start_time)
);

CREATE TABLE SENSOR_DATA (
    sensor_id VARCHAR(10) PRIMARY KEY,
    device_id VARCHAR(10) NOT NULL,
    temperature DECIMAL(5,2) NOT NULL,
    humidity DECIMAL(5,2) NOT NULL CHECK (humidity BETWEEN 0 AND 100),
    rain_status VARCHAR(20) NOT NULL CHECK (rain_status IN ('NO_RAIN','RAINING')),
    light_status VARCHAR(20) NOT NULL CHECK (light_status IN ('BRIGHT','DARK')),
    roof_status VARCHAR(20) NOT NULL CHECK (roof_status IN ('OPEN','CLOSED')),
    recorded_at DATETIME2 NOT NULL,
    CONSTRAINT FK_SENSOR_DEVICE FOREIGN KEY (device_id) REFERENCES DEVICE(device_id)
);

CREATE TABLE EVENT_LOG (
    event_id VARCHAR(10) PRIMARY KEY,
    warehouse_id VARCHAR(10) NOT NULL,
    device_id VARCHAR(10) NULL,
    batch_id VARCHAR(10) NULL,
    actor_user_id VARCHAR(10) NULL,
    event_type VARCHAR(30) NOT NULL,
    source VARCHAR(20) NOT NULL CHECK (source IN ('AUTO','MANUAL','WEB')),
    description NVARCHAR(500) NULL,
    created_at DATETIME2 NOT NULL,
    CONSTRAINT FK_EVENT_WAREHOUSE FOREIGN KEY (warehouse_id) REFERENCES WAREHOUSE(warehouse_id),
    CONSTRAINT FK_EVENT_DEVICE FOREIGN KEY (device_id) REFERENCES DEVICE(device_id),
    CONSTRAINT FK_EVENT_BATCH FOREIGN KEY (batch_id) REFERENCES DRYING_BATCH(batch_id),
    CONSTRAINT FK_EVENT_ACTOR FOREIGN KEY (actor_user_id) REFERENCES USERS(user_id)
);
GO
